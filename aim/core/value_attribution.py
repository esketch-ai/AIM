    def record_attribution(
        self,
        tenant_id: str,
        source_type: str,
        title: str,
        units_generated: int,
        unit_price: int,
        cost_incurred_krw: int = 0,
        evidence_tier: str = "C_ILLUSTRATIVE",
    ) -> AttributionEntry:
        gross = units_generated * unit_price
        net = gross - cost_incurred_krw

        entry = AttributionEntry(
            entry_id=f"ATTR_{uuid.uuid4().hex[:6].upper()}",
            tenant_id=tenant_id,
            source_type=source_type,
            title=title,
            units_generated=units_generated,
            unit_price=unit_price,
            gross_revenue_krw=gross,
            cost_incurred_krw=cost_incurred_krw,
            net_value_krw=net,
            evidence_tier=evidence_tier,
        )

        if tenant_id not in self.ledger:
            self.ledger[tenant_id] = []
        self.ledger[tenant_id].insert(0, entry)
        return entry

    def get_tenant_summary(self, tenant_id: str, monthly_fee_krw: int = 49000, business_name: str = "") -> TenantAttributionSummary:
        entries = self.ledger.get(tenant_id, [])
        total_rev = sum(e.gross_revenue_krw for e in entries)
        total_cost = sum(e.cost_incurred_krw for e in entries)
        net_ben = total_rev - total_cost

        # Total investment = subscription fee (2-month baseline amortized) + optional creator cost
        total_invested = (monthly_fee_krw * 2) + total_cost
        roi = round(total_rev / total_invested, 1) if total_invested > 0 else 0.0

        return TenantAttributionSummary(
            tenant_id=tenant_id,
            business_name=business_name or tenant_id,
            monthly_fee_krw=monthly_fee_krw,
            cumulative_revenue_krw=total_rev,
            cumulative_cost_krw=total_cost,
            net_benefit_krw=net_ben,
            roi_multiplier=roi,
            total_campaigns=len(entries),
            evidence_tier="C_ILLUSTRATIVE",
            entries=entries,
        )


