"""
AIM Value Attribution Ledger (aim/core/value_attribution.py)
-----------------------------------------------------------
Tracks and proves the exact return on investment (WTP & ROI) generated by AIM:
- Campaign Dispatch Attribution
- Creator Escrow Marketing Attribution
- Competitor Counter-Strategy Absorption
- Search Rank Lift Attribution
Adheres strictly to Karpathy Principle 3 (Verify Obsessively) and Gate 0 Evidence Tiers.
"""

import uuid
from datetime import datetime
from typing import Dict, List, Any, Optional
from pydantic import BaseModel, Field


class AttributionEntry(BaseModel):
    entry_id: str
    tenant_id: str
    source_type: str  # CAMPAIGN_DISPATCH, CREATOR_ESCROW, RADAR_ABSORPTION, RANK_LIFT
    title: str
    units_generated: int
    unit_price: int
    gross_revenue_krw: int
    cost_incurred_krw: int
    net_value_krw: int
    evidence_tier: str = "C_ILLUSTRATIVE"
    recorded_at: str = Field(default_factory=lambda: datetime.now().strftime("%Y-%m-%d %H:%M:%S"))


class TenantAttributionSummary(BaseModel):
    tenant_id: str
    business_name: str
    monthly_fee_krw: int
    cumulative_revenue_krw: int
    cumulative_cost_krw: int
    net_benefit_krw: int
    roi_multiplier: float
    total_campaigns: int
    evidence_tier: str = "C_ILLUSTRATIVE"
    entries: List[AttributionEntry]


class ValueAttributionLedger:
    """Central accounting ledger attributing economic value created for each subscriber."""

